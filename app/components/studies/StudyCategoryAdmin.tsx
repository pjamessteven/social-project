"use client";

import type { StudyCategoryKind } from "@/app/lib/study-category-urls";
import { useRouter } from "next/navigation";
import { useState } from "react";
import { Button } from "../ui/button";
import { Input } from "../ui/input";
import { Textarea } from "../ui/textarea";

/** English source values of a category (admins always edit English). */
export interface StudyCategorySource {
  id: number;
  kind: StudyCategoryKind;
  slug: string;
  name: string;
  description: string;
  sortOrder: number;
}

/**
 * Admin-only create/edit form for a study category. With `category` it edits
 * (and can delete) that category; otherwise it creates one of `kind`.
 * Translations are regenerated by scripts/generate-study-hub-translations.ts.
 */
export function StudyCategoryAdmin({
  kind,
  category,
  onDeletedHref,
}: {
  kind: StudyCategoryKind;
  category?: StudyCategorySource;
  /** Where to go after deleting the category */
  onDeletedHref?: string;
}) {
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [form, setForm] = useState({
    name: category?.name ?? "",
    slug: category?.slug ?? "",
    description: category?.description ?? "",
    sortOrder: String(category?.sortOrder ?? 0),
  });
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const kindLabel = kind === "topic" ? "topic" : "method";

  if (!open) {
    return (
      <Button variant="outline" size="sm" onClick={() => setOpen(true)}>
        {category ? `Edit ${kindLabel} (admin)` : `Add ${kindLabel} category`}
      </Button>
    );
  }

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    setBusy(true);
    setError(null);
    try {
      const response = await fetch(
        category
          ? `/api/studies/categories/${category.id}`
          : "/api/studies/categories",
        {
          method: category ? "PATCH" : "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            kind,
            name: form.name,
            slug: form.slug || undefined,
            description: form.description,
            sortOrder: Number(form.sortOrder) || 0,
          }),
        },
      );
      const data = await response.json();
      if (!response.ok) throw new Error(data.error || "Save failed");
      setOpen(false);
      router.refresh();
    } catch (err) {
      setError(err instanceof Error ? err.message : "Save failed");
    } finally {
      setBusy(false);
    }
  };

  const remove = async () => {
    if (!category || !confirm(`Delete "${category.name}"? Studies keep their other categories.`)) {
      return;
    }
    setBusy(true);
    const response = await fetch(`/api/studies/categories/${category.id}`, {
      method: "DELETE",
    });
    setBusy(false);
    if (!response.ok) {
      setError("Delete failed");
      return;
    }
    if (onDeletedHref) router.push(onDeletedHref);
    else router.refresh();
  };

  return (
    <form onSubmit={submit} className="max-w-2xl space-y-3 text-sm">
      <h3 className="text-base font-semibold">
        {category ? `Edit ${kindLabel}` : `New ${kindLabel} category`} (English)
      </h3>
      <Input
        placeholder="Name"
        value={form.name}
        onChange={(e) => setForm({ ...form, name: e.target.value })}
        required
      />
      <div className="flex gap-3">
        <Input
          placeholder="slug (from name if empty)"
          value={form.slug}
          onChange={(e) => setForm({ ...form, slug: e.target.value })}
        />
        <Input
          type="number"
          placeholder="Sort order"
          className="w-32"
          value={form.sortOrder}
          onChange={(e) => setForm({ ...form, sortOrder: e.target.value })}
        />
      </div>
      <Textarea
        placeholder="Description (1–2 sentences)"
        value={form.description}
        onChange={(e) => setForm({ ...form, description: e.target.value })}
        rows={3}
      />
      <p className="text-muted-foreground text-xs">
        Changing the name or description clears its translations; run
        scripts/generate-study-hub-translations.ts to regenerate them.
        Changing the slug changes the English URL.
      </p>
      {error && <p className="text-red-600">{error}</p>}
      <div className="flex gap-2">
        <Button type="submit" size="sm" disabled={busy}>
          {busy ? "Saving…" : "Save"}
        </Button>
        <Button
          type="button"
          size="sm"
          variant="ghost"
          onClick={() => setOpen(false)}
        >
          Cancel
        </Button>
        {category && (
          <Button
            type="button"
            size="sm"
            variant="destructive"
            className="ml-auto"
            onClick={remove}
            disabled={busy}
          >
            Delete
          </Button>
        )}
      </div>
    </form>
  );
}
